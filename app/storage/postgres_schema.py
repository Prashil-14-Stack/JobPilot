"""PostgreSQL schema initialization for JobPilot."""

from typing import Any


SCHEMA_STATEMENTS = (
    """
    CREATE TABLE IF NOT EXISTS jobs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source TEXT NOT NULL,
        source_job_id TEXT,
        title TEXT,
        company TEXT,
        location TEXT,
        country TEXT,
        remote_type TEXT,
        source_url TEXT,
        apply_url TEXT,
        description TEXT,
        content_mode TEXT DEFAULT 'FULL_CONTENT',
        canonical_role TEXT,
        matched_search_variant TEXT,
        search_task_id TEXT,
        posted_date TEXT,
        discovered_at TEXT,
        visa_status TEXT,
        visa_evidence TEXT,
        work_authorization_requirement TEXT,
        relevance_score DOUBLE PRECISION,
        relevance_level TEXT,
        match_reasons TEXT,
        missing_requirements TEXT,
        matched_skills TEXT,
        matched_experience TEXT,
        raw_provider_data TEXT,
        content_hash TEXT,
        first_seen_at TEXT,
        last_seen_at TEXT,
        processing_status TEXT DEFAULT 'NEW',
        review_status TEXT DEFAULT 'PENDING',
        application_status TEXT DEFAULT 'NOT_APPLIED',
        applied_at TEXT,
        contact_status TEXT DEFAULT 'NOT_CONTACTED',
        created_at TEXT NOT NULL,
        updated_at TEXT NOT NULL,
        UNIQUE(source, source_job_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS contacts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        contact_id TEXT NOT NULL UNIQUE,
        first_name TEXT,
        last_name TEXT,
        full_name TEXT,
        email TEXT,
        position TEXT,
        company TEXT,
        company_domain TEXT,
        linkedin_url TEXT,
        email_confidence INTEGER,
        email_verification_status TEXT,
        source TEXT DEFAULT 'Hunter',
        first_seen_at TEXT,
        last_seen_at TEXT,
        created_at TEXT,
        updated_at TEXT
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS company_domains (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        company TEXT NOT NULL UNIQUE,
        normalized_company TEXT NOT NULL,
        domain TEXT,
        status TEXT NOT NULL,
        confidence INTEGER DEFAULT 0,
        source TEXT,
        reason TEXT,
        first_resolved_at TEXT,
        last_resolved_at TEXT,
        created_at TEXT,
        updated_at TEXT
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_jobs_source ON jobs(source)",
    """
    CREATE INDEX IF NOT EXISTS idx_jobs_processing_status
    ON jobs(processing_status)
    """,
    "CREATE INDEX IF NOT EXISTS idx_jobs_content_hash ON jobs(content_hash)",
)


def initialize_postgres(connection: Any) -> None:
    """Create or update the initial JobPilot PostgreSQL tables."""
    with connection.cursor() as cursor:
        for statement in SCHEMA_STATEMENTS:
            cursor.execute(statement)

    connection.commit()
